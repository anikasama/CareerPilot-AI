def build_roadmap(missing_skills: list[str]) -> list[dict]:
    roadmap = []

    for skill in missing_skills:
        details = ROADMAP.get(
            skill,
            {
                "priority": "Medium",
                "difficulty": "Medium",
                "estimated_time": "1–2 Weeks",
                "learn": f"Build practical working knowledge of {skill}.",
                "project": f"Create a small practical project using {skill}.",
            },
        )

        roadmap.append(
            {
                "skill": skill,
                **details,
                "progress": 0,
            }
        )

    priority_order = {
        "High": 0,
        "Medium": 1,
        "Low": 2,
    }

    roadmap.sort(
        key=lambda item: (
            priority_order.get(item["priority"], 1),
            item["skill"],
        )
    )

    return roadmap